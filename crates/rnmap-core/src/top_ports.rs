/// Return the top `n` distinct TCP ports.
pub fn top_n(n: usize) -> Vec<u16> {
    let mut seen = std::collections::BTreeSet::new();
    let mut out = Vec::new();
    for &p in TOP {
        if seen.insert(p) {
            out.push(p);
            if out.len() >= n {
                break;
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn top_10_includes_22_and_80() {
        let t = top_n(10);
        assert!(t.contains(&22));
        assert!(t.contains(&80));
        assert!(t.contains(&443));
    }
    #[test]
    fn no_duplicates() {
        let t = top_n(150);
        let s: std::collections::BTreeSet<_> = t.iter().collect();
        assert_eq!(t.len(), s.len());
    }
}
